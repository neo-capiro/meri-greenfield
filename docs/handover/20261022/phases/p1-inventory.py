# P1 inventory: every timeout / deadline / lease / poll row in adj-e's three sweeps of 4797f7da, re-anchored to the P1 base.
# Usage: PYTHONIOENCODING=utf-8 python p1-inventory.py <meri worktree> <base sha> [<previous base sha>] > P1-INVENTORY.md
# For each row it records the sweep's file:line, value and how it was set, whether the row is an unset default (library default,
# module default no caller sets, or unset), and whether the cited file changed between 4797f7da and the base (re-check needed).
# With a previous base, a last column says whether the cited file changed between the previous base and this one.
# The sweeps are local planner files: an implementer uses the committed P1-INVENTORY.md, not this script.
import os, re, subprocess, sys
wt, base = sys.argv[1], sys.argv[2]
prev = sys.argv[3] if len(sys.argv) > 3 else None
notes = os.path.join('C:' + os.sep, 'dev', 'fable', 'adj-reports', 'adj-e-notes')
def git(*args):
    return subprocess.run(['git', '-C', wt, *args], capture_output=True, text=True, encoding='utf8').stdout
changed = set(git('diff', '--name-only', '4797f7da', base).split())
moved = set(git('diff', '--name-only', prev, base).split()) if prev else set()
tracked = set(git('ls-tree', '-r', '--name-only', base).split())
FILE = re.compile(r'([A-Za-z0-9_./@-]+\.(?:mjs|js|ts|py|json|cjs))(?::([0-9,\- ]+))?')
def resolve(cell):
    m = FILE.search(cell)
    if not m: return None
    name = m.group(1)
    if name in tracked: return name
    hits = [t for t in tracked if t.endswith('/' + name)]
    return hits[0] if len(hits) == 1 else None
UNSET = re.compile(r'library default|^default|unset|passes none|nobody|not set|module default|explicit default', re.I)
ID = re.compile(r'^[A-Z]{1,3}\d+[a-z]?$')
rows = []
for sweep, area in (('sweep-runner.md', 'runner'), ('sweep-control.md', 'control'), ('sweep-owner-proxy.md', 'owner/proxy')):
    n = 0
    for line in open(os.path.join(notes, sweep), encoding='utf8'):
        if not line.startswith('| ') or 'file:line' in line: continue
        cells = [c.strip() for c in line.strip().strip('|').split('|')]
        at = next((i for i, c in enumerate(cells[:4]) if i >= 1 and FILE.search(c)), None)
        if at is None or len(cells) < at + 4: continue
        n += 1
        head = cells[0].split(' ', 1)
        if ID.match(head[0]):
            rid = head[0]
            comp = cells[1] if at == 3 else (head[1] if len(head) > 1 else '')
        else:
            rid, comp = f'{area[0].upper()}{n:03d}', cells[0]
        name, where, value, how = cells[at - 1], cells[at], cells[at + 1], cells[at + 3]
        path = resolve(where)
        status = 'library' if path is None else ('changed' if path in changed else 'same')
        rows.append((area, rid, comp, name, where, value, how, bool(UNSET.search(how)), status, path is not None and path in moved))
print('# P1 inventory (generated by `p1-inventory.py`; do not edit by hand)\n')
print(f'Source: adj-e sweeps of `4797f7da` (`adj-reports/adj-e-notes/sweep-*.md`). Base for P1: `{base}`.')
print('`unset` = library default, a module default no caller sets, or unset. `file`: `same` = cited file unchanged since 4797f7da;')
print('`changed` = re-locate the line at the base; `library` = outside the repo (an installed package default).\n')
count = lambda a: sum(1 for r in rows if r[0] == a and r[7])
print(f'Rows: {len(rows)}; unset defaults: {sum(r[7] for r in rows)} (runner {count("runner")}, control {count("control")}, owner/proxy {count("owner/proxy")}).\n')
if prev:
    print(f'Last column: `moved` = the cited file changed between the previous base `{prev}` and `{base}` (re-locate it again); '
          f'{sum(r[9] for r in rows)} rows.\n')
extra = f' since {prev} |' if prev else ''
for area in ('runner', 'control', 'owner/proxy'):
    print(f'## {area}\n\n| id | component | name | file:line @4797f7da | value | how set | unset | file |{extra}\n|---|---|---|---|---|---|---|---|' + ('---|' if prev else ''))
    for r in rows:
        if r[0] == area:
            cells = [r[1], r[2], r[3], r[4], r[5], r[6], 'yes' if r[7] else '', r[8]] + (['moved' if r[9] else ''] if prev else [])
            print('| ' + ' | '.join(c.replace('|', '/') for c in cells) + ' |')
    print()
