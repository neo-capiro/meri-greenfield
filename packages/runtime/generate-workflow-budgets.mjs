import {pathToFileURL} from 'node:url';
import {WORKFLOW_BUDGETS,fixedHotPathBudget} from './hot-path-budgets.mjs';
const workflowTimers=Object.freeze(Object.fromEntries(['objective.lifecycle.poll','objective.lifecycle.retry'].map(id=>[id,fixedHotPathBudget(id)])));
export const workflowBudgetsPath=new URL('../../apps/control/conversations/hot-path-budgets.generated.ts',import.meta.url);
export function renderWorkflowBudgets(){
 return '// Generated by packages/runtime/generate-workflow-budgets.mjs. Edit the canonical table, then regenerate.\n'+
  'export const WORKFLOW_BUDGETS = Object.freeze('+JSON.stringify(WORKFLOW_BUDGETS,null,2)+' as const);\n'+
  'export const WORKFLOW_TIMER_BUDGETS = Object.freeze('+JSON.stringify(workflowTimers,null,2)+' as const);\n';
}
if(process.argv[1]&&import.meta.url===pathToFileURL(process.argv[1]).href)await writeFile(workflowBudgetsPath,renderWorkflowBudgets());
