// Fixed-schema distribution generator. Importing it performs no generation.
import { readFile, mkdir, writeFile } from 'node:fs/promises';
import { createHash } from 'node:crypto';
import { resolve } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const HERE = new URL('./', import.meta.url);
const EXPECTED = 'e3de878198bbd557843ac440e48664ad5175eecd99f7ec932021ffc465bf8c5b';
const digest = raw => createHash('sha256').update(raw).digest('hex');

export async function generateContracts({ check = false } = {}) {
  const raw = await readFile(new URL('meri.schema.json', HERE));
  if (raw.length !== 50043 || digest(raw) !== EXPECTED) throw Error('Frozen0.1.0 schema drift');
  const schema = JSON.parse(raw);
  const [{ default: Ajv }, { default: addFormats }, { default: standalone }, { build }, { compile }] = await Promise.all([
    import('ajv/dist/2020.js'), import('ajv-formats'), import('ajv/dist/standalone/index.js'),
    import('esbuild'), import('json-schema-to-typescript'),
  ]);
  const ajv = new Ajv({ strict: true, allErrors: true, code: { source: true, esm: true } });
  addFormats(ajv);
  ajv.addSchema(schema);
  const eventRef = schema.$id + '#/$defs/UIEvent';
  ajv.compile({ $ref: eventRef });
  const source = standalone(ajv, { validateUIEvent: eventRef });
  const bundled = await build({ absWorkingDir: fileURLToPath(HERE), stdin: { contents: source, sourcefile: 'generated-validator.mjs', resolveDir: fileURLToPath(HERE) },
    bundle: true, write: false, platform: 'browser', format: 'esm', target: 'es2022', legalComments: 'inline', metafile: true });
  if (Object.values(bundled.metafile.outputs).some(output => output.imports.length)) throw Error('Browser validator external import');
  const declarations = await compile({ title: 'UIEvent', $ref: '#/$defs/UIEvent', $defs: schema.$defs }, 'UIEvent', {
    bannerComment: '// Generated from frozen meri.schema.json by generate.mjs. Do not edit.',
    additionalProperties: false, style: { singleQuote: true },
  });
  const variants = schema.$defs.UIEvent.oneOf.map(event => event.properties.type.const);
  const metadata = { contractVersion: '0.1.0', schemaId: schema.$id, schemaSha256: EXPECTED, schemaBytes: raw.length, uiEventVariants: variants };
  const outputs = new Map([
    ['browser.mjs', '// Generated; validation checks structure only.\n' + bundled.outputFiles[0].text],
    ['contracts.d.ts', declarations],
    ['index.d.ts', "export type * from './contracts.js';\nexport { validateUIEvent } from './browser.js';\n"],
    ['browser.d.ts', "import type { UIEvent } from './contracts.js';\nexport declare const validateUIEvent: ((value: unknown) => value is UIEvent) & { errors?: readonly unknown[] | null };\n"],
    ['metadata.mjs', 'const value = ' + JSON.stringify(metadata, null, 2) + ';\nObject.freeze(value.uiEventVariants);\nexport const metadata = Object.freeze(value);\n'],
    ['metadata.d.ts', 'export declare const metadata: Readonly<' + JSON.stringify(metadata, null, 2).replace('"uiEventVariants": [', '"uiEventVariants": readonly [') + '>;\n'],
  ]);
  // Validate every output before writing any. --check is strictly read-only.
  if (check) {
    for (const [name, content] of outputs) {
      if (await readFile(new URL('dist/' + name, HERE), 'utf8') !== content) throw Error('Generated drift: ' + name);
    }
  } else {
    await mkdir(new URL('dist/', HERE), { recursive: true });
    for (const [name, content] of outputs) await writeFile(new URL('dist/' + name, HERE), content, 'utf8');
  }
  return [...outputs].map(([path, content]) => ({ path, bytes: Buffer.byteLength(content), sha256: digest(content) }));
}

export async function main(argv) {
  if (argv.length === 1 && argv[0] === '--help') {
    process.stdout.write('Usage: node generate.mjs [--check|--help]\nBuild fixed public contracts, or check generated bytes without writing. Exit0 success; exit1 invalid arguments, schema/build/drift failure. No network.\n');
    return;
  }
  if (argv.length > 1 || (argv.length === 1 && argv[0] !== '--check')) throw Error('Usage: node generate.mjs [--check|--help]');
  const records = await generateContracts({ check: argv[0] === '--check' });
  process.stdout.write(JSON.stringify({ schema: 'meri-contract-distribution/1', check: argv[0] === '--check', records }) + '\n');
}

if (process.argv[1] && pathToFileURL(resolve(process.argv[1])).href === import.meta.url) {
  main(process.argv.slice(2)).catch(error => { process.stderr.write(error.message + '\n'); process.exitCode = 1; });
}
