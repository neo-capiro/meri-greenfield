"""Pure session-footer parsing for the discovered Hermes 0.20.0 CLI.

Installed cli.py emits a standalone footer to stderr in quiet query mode.
Its fresh IDs and compression continuations use YYYYMMDD_HHMMSS plus six
lowercase UUID hex characters. This is text identification, not authentication
of a session or proof that its work was accepted.
"""

from collections.abc import Iterable
import datetime as dt
import re


_SESSION_ID = re.compile(r"[0-9]{8}_[0-9]{6}_[0-9a-f]{6}")
_FOOTER = re.compile(r"session_id: ([0-9]{8}_[0-9]{6}_[0-9a-f]{6})")


def is_valid_hermes_session_id(value: object) -> bool:
    """Accept only the timestamp/UUID form generated by the installed CLI."""
    if not isinstance(value, str) or _SESSION_ID.fullmatch(value) is None:
        return False
    try:
        dt.datetime.strptime(value[:15], "%Y%m%d_%H%M%S")
    except ValueError:
        return False
    return True


def session_footer_ids(lines: Iterable[str], *, stream: str) -> list[str]:
    """Return distinct exact stderr footer IDs, preserving discovery order.

    Stdout contains agent prose and source snippets and is never an ID source.
    Strip only one line terminator; indentation, quotes, suffixes, ANSI escapes,
    malformed timestamps and other incidental text must not become IDs.
    Conflicting valid footers remain distinct so the launcher's existing
    exactly-one-ID gate fails instead of guessing which one to resume.
    """
    if stream != "stderr":
        return []
    result = []
    for line in lines:
        match = _FOOTER.fullmatch(line.removesuffix("\n").removesuffix("\r"))
        if match and is_valid_hermes_session_id(match[1]) and match[1] not in result:
            result.append(match[1])
    return result
