/** Retained PDF reads through the real application, immutable publication and session owners.
 * Scripted SQL/object transport and synthetic PDF bytes only; no renderer, database or provider qualification. */
import test from 'node:test';
import assert from 'node:assert/strict';
import {randomUUID} from 'node:crypto';
import {createDocumentApplication} from '../index.mjs';
import {createLocalDocumentPorts} from '../local/ports.mjs';
import {nativeDocumentFixture,sha} from '../../../artifacts/test/native-document-fixture.mjs';
import {realPdf} from '../../../artifacts/test/pdf-fixtures.mjs';
import {NOW,id} from '../../../artifacts/storage/test/sql-fixture.mjs';

const binding={tenantId:id(100),actorId:id(101),conversationId:id(102),runId:id(103),attemptId:id(104),workerId:id(105),writerFence:1};
const clientId=id(106),scopes=[{tenantId:binding.tenantId,kind:'client',resourceId:clientId,policyRevision:'policy1'}];
const request={operation:'create_word',format:'pdf',title:'Retained brief',content:{blocks:[{kind:'paragraph',runs:[{text:'Retained PDF'}]}]}};
async function fixture(t,{changeRecord}={}){
 const documents=nativeDocumentFixture({binding,scopes}),bytes=realPdf(['Retained PDF']);
 const executor={async execute(call){documents.state.executions.push(call);return {bytes,inspection:{sha256:sha(bytes),bytes:bytes.length,format:'pdf',nativeOpened:false,rendered:false,recalculated:false,members:[],details:{conversionCompleted:true,renderInspection:'pending',sourceDocxSha256:'a'.repeat(64)}}};}};
 const retained=await documents.owner({executor}).execute({deliveryId:'prior-pdf',baseVersionId:null,request});
 const state={closed:false,revoked:false,artifactChecks:0},now=()=>NOW;
 const ports=createLocalDocumentPorts({binding,scopes,clientId,deadlineMs:NOW+25000,now,state});t.after(()=>ports.sessions.close());
 const versions=changeRecord?{...documents.options.versions,async read(...args){return changeRecord(await documents.options.versions.read(...args));}}:documents.options.versions;
 const artifactOptions={...documents.options,versions,authorize:ports.authorize,now,ids:()=>({artifactId:randomUUID(),versionId:randomUUID(),objectId:randomUUID()}),executor:{async execute(){assert.fail('read or refused write invoked a generator');}}};
 const app=createDocumentApplication({sessions:ports.sessions,selectedClientId:clientId,artifactOptions,now,limits:{maxRequestMs:5000,maxRequestBytes:131072,maxResponseBytes:1048576},enabled:true});
 const session=await ports.sessions.issue({identityCredential:ports.nativeCredential});
 const post=(route,body)=>app.handle(new Request('https://meri.synthetic.invalid/api/documents/'+route,{method:'POST',headers:{authorization:'Bearer '+session.credential,'content-type':'application/json'},body:JSON.stringify(body)}));
 return {documents,state,bytes,version:retained.version,post};
}

test('retained PDF inspect/download works without PDF writer admission or a renderer',async t=>{
 const x=await fixture(t),body={versionId:x.version.versionId};
 const inspect=await x.post('inspect',body);assert.equal(inspect.status,200,await inspect.clone().text());
 const value=await inspect.json();assert.deepEqual(value.version,x.version);assert.equal(value.inspection.format,'pdf');assert.equal(value.inspection.currentBytesVerified,true);
 assert.equal(value.inspection.nativeOpened,false);assert.equal(value.inspection.rendered,false);assert.equal(value.inspection.recalculated,false);assert.equal(value.version.previewStatus,'pending');
 const download=await x.post('download',body);assert.equal(download.status,200,await download.clone().text());
 assert.equal(download.headers.get('content-type'),'application/pdf');assert.equal(download.headers.get('content-disposition'),'attachment; filename="Retained brief.pdf"');
 assert.equal(download.headers.get('cache-control'),'no-store');assert.deepEqual(Buffer.from(await download.arrayBuffer()),x.bytes);
 assert.equal(x.documents.state.executions.length,1,'only the prior publication generated bytes');assert.equal(x.documents.state.rows.size,1,'reads create no delivery');
});

test('retained PDF read support does not admit PDF create/revise or preview routes',async t=>{
 const x=await fixture(t);
 for(const route of ['create','revise']){
  const response=await x.post(route,{deliveryId:'new-'+route,request,...(route==='revise'?{baseVersionId:x.version.versionId}:{})});
  assert.equal(response.status,400);assert.deepEqual((await response.json()).error,{code:'INVALID_REQUEST',outcome:'NOT_DISPATCHED'});
 }
 for(const route of ['preview','preview-publish']){const response=await x.post(route,{versionId:x.version.versionId});assert.equal(response.status,503);assert.equal((await response.json()).error.code,'PREVIEW_UNAVAILABLE');}
 assert.equal(x.documents.state.executions.length,1);assert.equal(x.documents.state.rows.size,1);
});

for(const violation of ['session','suppression','bytes','foreign-client','foreign-actor','MIME','filename','version'])test(`retained PDF ${violation} refuses inspect and download with writer admission off`,async t=>{
 const changeRecord=record=>{
  if(violation==='foreign-client')record.version.scopes=[{...scopes[0],resourceId:id(998)}];
  if(violation==='foreign-actor')record.version.binding.actorId=id(998);
  if(violation==='MIME')record.version.mimeType='text/plain; charset=utf-8';
  if(violation==='filename')record.version.filename='Other.pdf';
  if(violation==='version')record.version.versionId=id(998);
  return record;
 };
 const x=await fixture(t,{changeRecord});
 if(violation==='session')x.state.revoked=true;
 if(violation==='suppression')x.documents.sql.suppressed.add(`${binding.tenantId}:artifact:${x.version.artifactId}`);
 if(violation==='bytes')for(const key of x.documents.state.objects.keys())x.documents.state.objects.set(key,Buffer.from('wrong bytes'));
 for(const route of ['inspect','download']){const response=await x.post(route,{versionId:x.version.versionId});assert.notEqual(response.status,200);assert.equal(response.headers.get('cache-control'),'no-store');}
 assert.equal(x.documents.state.executions.length,1);assert.equal(x.documents.state.rows.size,1);
});
